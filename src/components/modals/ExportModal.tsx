import React, { useState } from 'react';
import { X, FileSpreadsheet, FileText, Printer, Check, Download } from 'lucide-react';
import { EventData, BudgetItem, RunOfShowItem } from '@/types';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  activeEvent: EventData;
  budgetItems: BudgetItem[];
  runOfShow: RunOfShowItem[];
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  activeEvent,
  budgetItems,
  runOfShow,
}) => {
  const [downloadSuccess, setDownloadSuccess] = useState<string | null>(null);

  if (!isOpen) return null;

  const downloadCSV = () => {
    const headers = ['Item Name', 'Vendor', 'Category', 'Budgeted ($)', 'Actual ($)', 'Status', 'Receipt Attached'];
    const rows = budgetItems.map((b) => [
      `"${b.name.replace(/"/g, '""')}"`,
      `"${b.vendor.replace(/"/g, '""')}"`,
      b.category,
      b.budgeted,
      b.actual,
      b.status,
      b.receiptAttached ? 'Yes' : 'No',
    ]);

    const csvContent = 'data:text/csv;charset=utf-8,' + [headers.join(','), ...rows.map((e) => e.join(','))].join('\n');
    const encodedUri = encodeURI(csvContent);
    const link = document.createElement('a');
    link.setAttribute('href', encodedUri);
    link.setAttribute('download', `${activeEvent.title.replace(/\s+/g, '_')}_Budget_Ledger.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);

    setDownloadSuccess('CSV Budget Ledger Downloaded');
    setTimeout(() => setDownloadSuccess(null), 3000);
  };

  const downloadRunOfShow = () => {
    const lines = [
      `# Production Run-of-Show: ${activeEvent.title}`,
      `Location: ${activeEvent.location}`,
      `Date: ${activeEvent.date}`,
      `Generated by EventSphere AI Autonomous Planning Assistant`,
      '',
      '---',
      '',
    ];

    runOfShow.forEach((r) => {
      lines.push(`### ${r.time} - ${r.title}`);
      lines.push(`- Duration: ${r.durationMinutes} mins`);
      lines.push(`- Zone/Location: ${r.location}`);
      lines.push(`- Lead Person: ${r.leadPerson}`);
      lines.push(`- Notes: ${r.notes}`);
      lines.push(`- Status: ${r.status}`);
      lines.push('');
    });

    const blob = new Blob([lines.join('\n')], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${activeEvent.title.replace(/\s+/g, '_')}_Run_Of_Show.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    setDownloadSuccess('Run-of-Show Production Pack Downloaded');
    setTimeout(() => setDownloadSuccess(null), 3000);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-stone-900/40 backdrop-blur-xs">
      <div className="w-full max-w-md rounded-2xl border border-stone-200 bg-white p-6 shadow-2xl">
        <div className="flex items-center justify-between pb-4 border-b border-stone-100">
          <div>
            <h3 className="font-editorial text-lg font-bold text-stone-900">
              Export Production Pack
            </h3>
            <p className="text-xs text-stone-500">{activeEvent.title}</p>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-stone-400 hover:text-stone-700 hover:bg-stone-100"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        <div className="mt-4 space-y-3">
          <button
            onClick={downloadCSV}
            className="w-full flex items-center justify-between rounded-xl border border-stone-200 p-3.5 hover:border-[#9D3E1A]/50 hover:bg-[#F4ECE1]/30 transition group text-left"
          >
            <div className="flex items-center gap-3">
              <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-emerald-50 text-emerald-700">
                <FileSpreadsheet className="h-5 w-5" />
              </div>
              <div>
                <p className="text-xs font-bold text-stone-900 group-hover:text-[#9D3E1A]">
                  Itemized Budget &amp; Expenses (.CSV)
                </p>
                <p className="text-[11px] text-stone-500">
                  Spreadsheet of all allocated and actual costs, vendors, and receipts
                </p>
              </div>
            </div>
            <Download className="h-4 w-4 text-stone-400 group-hover:text-[#9D3E1A]" />
          </button>

          <button
            onClick={downloadRunOfShow}
            className="w-full flex items-center justify-between rounded-xl border border-stone-200 p-3.5 hover:border-[#9D3E1A]/50 hover:bg-[#F4ECE1]/30 transition group text-left"
          >
            <div className="flex items-center gap-3">
              <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-amber-50 text-amber-700">
                <FileText className="h-5 w-5" />
              </div>
              <div>
                <p className="text-xs font-bold text-stone-900 group-hover:text-[#9D3E1A]">
                  Day-of Run-of-Show Protocol (.MD / Text)
                </p>
                <p className="text-[11px] text-stone-500">
                  Minute-by-minute cues for production crew, sound leads, and catering
                </p>
              </div>
            </div>
            <Download className="h-4 w-4 text-stone-400 group-hover:text-[#9D3E1A]" />
          </button>

          <button
            onClick={() => window.print()}
            className="w-full flex items-center justify-between rounded-xl border border-stone-200 p-3.5 hover:border-[#9D3E1A]/50 hover:bg-[#F4ECE1]/30 transition group text-left"
          >
            <div className="flex items-center gap-3">
              <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-stone-100 text-stone-700">
                <Printer className="h-5 w-5" />
              </div>
              <div>
                <p className="text-xs font-bold text-stone-900 group-hover:text-[#9D3E1A]">
                  Print Production Sheet (PDF)
                </p>
                <p className="text-[11px] text-stone-500">
                  Formatted overview ready for physical clipboard briefing
                </p>
              </div>
            </div>
            <Printer className="h-4 w-4 text-stone-400 group-hover:text-[#9D3E1A]" />
          </button>
        </div>

        {downloadSuccess && (
          <div className="mt-4 flex items-center gap-2 rounded-xl bg-emerald-50 p-2.5 text-xs font-semibold text-emerald-800 border border-emerald-200">
            <Check className="h-4 w-4 text-emerald-600" />
            <span>{downloadSuccess}</span>
          </div>
        )}
      </div>
    </div>
  );
};
